"""Build fonts/icons.ttf and src/icons.rs from the Lucide icon font.

Only the icons named in src/icons.rs are kept, and they are moved to the Supplementary
Private Use Area (U+F0000...) so they can never collide with glyphs in a text font
(Inter uses the basic Private Use Area for its own alternates).

Usage: python tools/make-icons.py [extra-icon-name ...]
"""
import json, re, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.subset import Subsetter, Options

root = Path(__file__).resolve().parent.parent
info = json.loads((root / "fonts" / "lucide-info.json").read_text(encoding="utf-8"))
rs = (root / "src" / "icons.rs").read_text(encoding="utf-8")
names = [m.lower().replace("_", "-") for m in re.findall(r"pub const ([A-Z0-9_]+):", rs)]
for extra in sys.argv[1:]:
    if extra not in names:
        names.append(extra)
missing = [n for n in names if n not in info]
if missing:
    sys.exit("unknown icons: " + ", ".join(missing))

font = TTFont(root / "fonts" / "lucide.ttf")
old = {n: int(info[n]["encodedCode"].lstrip("\\"), 16) for n in names}
opts = Options()
opts.layout_features = []
opts.name_IDs = [1, 2]
opts.notdef_outline = True
sub = Subsetter(opts)
sub.populate(unicodes=list(old.values()))
sub.subset(font)

best = font.getBestCmap()
new_map = {0xF0000 + i: best[old[n]] for i, n in enumerate(names)}
from fontTools.ttLib.tables._c_m_a_p import CmapSubtable
table = CmapSubtable.newSubtable(12)
table.platformID, table.platEncID, table.language = 3, 10, 0
table.cmap = new_map
font["cmap"].tables = [table]
font.save(root / "fonts" / "icons.ttf")

lines = ["//! Icon codepoints in fonts/icons.ttf (generated by tools/make-icons.py from Lucide).", "#![allow(dead_code)]"]
for i, n in enumerate(names):
    lines.append('pub const %s: &str = "\\u{%x}";' % (n.upper().replace("-", "_"), 0xF0000 + i))
(root / "src" / "icons.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(names), "icons,", (root / "fonts" / "icons.ttf").stat().st_size, "bytes")
